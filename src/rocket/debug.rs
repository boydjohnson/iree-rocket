//! Small debug helper for inspecting a constructed regcmd stream --
//! decodes each RegCmd's (domain, offset, value) and resolves offset
//! to its REG_* name from rkt_registers.h, so a binary's constructed
//! stream can be read/diffed against an externally-decoded one (e.g.
//! the conv.rknn regcmd decode in rknpu-spelunking/NOTES.md) without
//! hand-translating hex offsets back to register names each time.
//!
//! register_name()'s table is generated from rkt_registers.h's
//! `#define REG_*` lines (Python one-liner, not hand-transcribed --
//! see rknpu-spelunking session notes if it needs regenerating after
//! rkt_registers.h changes).

use crate::rocket::builders::RegCmd;

pub fn decode(cmd: &RegCmd) -> (u32, u32, u32) {
    let word = cmd.0;
    let domain = ((word >> 48) & 0xFFFF) as u32;
    let value = ((word >> 16) & 0xFFFF_FFFF) as u32;
    let offset = (word & 0xFFFF) as u32;
    (domain, offset, value)
}

pub fn domain_name(domain: u32) -> &'static str {
    use crate::rocket::builders::{
        DOMAIN_CNA, DOMAIN_CORE, DOMAIN_DPU, DOMAIN_DPU_RDMA, DOMAIN_GLOBAL, DOMAIN_PC,
        DOMAIN_PPU, DOMAIN_PPU_RDMA,
    };
    match domain {
        d if d == DOMAIN_CNA => "CNA",
        d if d == DOMAIN_PC => "PC",
        d if d == DOMAIN_CORE => "CORE",
        d if d == DOMAIN_DPU => "DPU",
        d if d == DOMAIN_DPU_RDMA => "DPU_RDMA",
        d if d == DOMAIN_PPU => "PPU",
        d if d == DOMAIN_PPU_RDMA => "PPU_RDMA",
        // DOMAIN_GLOBAL is unconfirmed -- see builders.rs and NOTES.md.
        d if d == DOMAIN_GLOBAL => "GLOBAL?",
        _ => "?",
    }
}

