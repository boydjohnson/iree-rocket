/// Prints one line per RegCmd: index, resolved domain name, raw
/// domain/offset/value hex, and resolved register name (or "?" if
/// the offset isn't in rkt_registers.h). Written to stderr so it's
/// visible even if the process later hangs waiting on the NPU.
pub fn dump_cmds(label: &str, cmds: &[RegCmd]) {
    eprintln!("--- regcmd dump: {} ({} entries) ---", label, cmds.len());
    for (i, c) in cmds.iter().enumerate() {
        let (domain, offset, value) = decode(c);
        let dname = domain_name(domain);
        let rname = register_name(offset).unwrap_or("?");
        eprintln!(
            "[{:3}] domain={:<10} (0x{:04x})  off=0x{:04x}  val=0x{:08x}  {}",
            i, dname, domain, offset, value, rname
        );
    }
}
